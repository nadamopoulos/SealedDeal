export const COMP_CATEGORIES = ['All', 'QSR', 'Fast Casual', 'Casual Dining', 'Coffee & Beverage'] as const;

export function searchComps(query: string, category?: string): CompConcept[] {
  const q = query.toLowerCase().trim();
  return COMP_DATABASE.filter((comp) => {
    const matchesCategory = !category || category === 'All' || comp.category === category;
    const matchesQuery = !q || comp.name.toLowerCase().includes(q) || comp.category.toLowerCase().includes(q);
    return matchesCategory && matchesQuery;
  });
}
